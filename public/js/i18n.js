function preferredLanguage(list) {
  const requested = Array.isArray(list) && list.length
    ? list
    : (navigator.languages && navigator.languages.length
      ? navigator.languages
      : [navigator.language || "en"]);
  for (const tag of requested) {
    const base = String(tag || "").toLowerCase().split("-")[0];
    if (messages[base]) return base;
  }
  return "en";
}

const languageStorageKey = "house-lang";
let language = "en";

function storedLanguage() {
  try {
    const saved = localStorage.getItem(languageStorageKey);
    if (saved && messages[saved]) return saved;
  } catch (error) {
    return null;
  }
  return null;
}

function t(key, vars) {
  const table = messages[language] || messages.en;
  let text = table[key] ?? messages.en[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

function syncLangSwitch() {
  document.querySelectorAll(".lang-switch [data-lang]").forEach((button) => {
    button.setAttribute("aria-pressed", button.getAttribute("data-lang") === language ? "true" : "false");
  });
}

function applyI18n(lang, persist) {
  if (lang && messages[lang]) language = lang;
  else language = storedLanguage() || preferredLanguage();
  if (persist) {
    try {
      localStorage.setItem(languageStorageKey, language);
    } catch (error) {
      /* The page still switches for this visit. */
    }
  }
  document.documentElement.lang = language;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const value = t(el.getAttribute("data-i18n"));
    const attr = el.getAttribute("data-i18n-attr");
    if (attr) {
      el.setAttribute(attr, value);
      return;
    }
    if (el.children.length > 0) return;
    el.textContent = value;
  });
  syncLangSwitch();
  document.dispatchEvent(new CustomEvent("languagechange"));
}

document.querySelectorAll(".lang-switch [data-lang]").forEach((button) => {
  button.addEventListener("click", () => {
    applyI18n(button.getAttribute("data-lang"), true);
  });
});

applyI18n();
window.t = t;
window.applyI18n = applyI18n;
window.preferredLanguage = preferredLanguage;
